def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if files are stale")
    args = ap.parse_args()

    rows, orphan = _joined()
    targets = {
        os.path.join(ROOT, "ATLAS.md"): build_markdown(rows, orphan),
        os.path.join(ROOT, "docs", "atlas.html"): build_html(rows, orphan),
    }

    stale = []
    for path, content in targets.items():
        existing = None
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as fh:
                existing = fh.read()
        if existing == content:
            print("unchanged  {}".format(os.path.relpath(path, ROOT)))
            continue
        if args.check:
            stale.append(os.path.relpath(path, ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        print("wrote      {}".format(os.path.relpath(path, ROOT)))

    if stale:
        print(
            "\nThese generated files are stale: {}\n"
            "Run: python scripts/build_atlas.py".format(", ".join(stale))
        )
        return 1
    print("\n{} entries, {} without a detector".format(len(rows), len(orphan)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
