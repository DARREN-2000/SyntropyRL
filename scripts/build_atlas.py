"""Generate ATLAS.md and docs/atlas.html from the detector registry.

The Atlas is data (src/syntropyrl/atlas.py) and the detectors are code
(src/syntropyrl/detectors/). This script joins them, so the published docs can
never describe a detector that does not ship, and a shipped detector can never
be missing from the docs. CI runs `--check` to enforce that.

    python scripts/build_atlas.py            # write the files
    python scripts/build_atlas.py --check    # fail if regeneration changes them
"""

from __future__ import annotations

import argparse
import html
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from syntropyrl.atlas import ENTRIES, FAMILY_BLURB, FAMILY_ORDER  # noqa: E402
from syntropyrl.detectors import catalog  # noqa: E402

BANNER = "<!-- generated by scripts/build_atlas.py - edit src/syntropyrl/atlas.py instead -->"


def _joined():
    """Join Atlas entries with the detector that implements them."""
    det = {d["code"]: d for d in catalog()}
    missing = sorted(set(det) - set(ENTRIES))
    if missing:
        raise SystemExit(
            "these detectors have no Atlas entry: {}\n"
            "Add them to src/syntropyrl/atlas.py.".format(", ".join(missing))
        )
    orphan = sorted(set(ENTRIES) - set(det))
    rows = []
    for fam in FAMILY_ORDER:
        for code, e in ENTRIES.items():
            if e["family"] != fam:
                continue
            rows.append({"code": code, "detector": det.get(code), **e})
    return rows, orphan


# --------------------------------------------------------------------------
# ATLAS.md
# --------------------------------------------------------------------------
def build_markdown(rows, orphan) -> str:
    out = [
        BANNER,
        "",
        "# The RL Failure Atlas",
        "",
        "Every way a reinforcement learning run can quietly fail, what it looks like,",
        "and what to do about it. Each entry that has a detector is checked automatically",
        "by `syntropyrl`; entries without one are still worth reading.",
        "",
        "Browsable version: <https://syntropyrl.dev/atlas.html>",
        "",
        "## Index",
        "",
        "| Code | Failure mode | Family | Detector |",
        "|---|---|---|---|",
    ]
    for r in rows:
        out.append(
            "| [{code}](#{anchor}) | {title} | {family} | {det} |".format(
                code=r["code"],
                anchor=r["code"].lower(),
                title=r["title"],
                family=r["family"],
                det="yes" if r["detector"] else "not yet",
            )
        )
    if orphan:
        out += ["", "Entries without a detector yet: " + ", ".join(orphan) + "."]

    current = None
    for r in rows:
        if r["family"] != current:
            current = r["family"]
            out += ["", "---", "", "## {}".format(current.title()), "", "*{}*".format(FAMILY_BLURB.get(current, ""))]
        out += ["", "### {} - {}".format(r["code"], r["title"]), ""]
        if r.get("aka"):
            out.append("*Also called: {}*".format(", ".join(r["aka"])))
            out.append("")
        out += [
            "**Symptom.** {}".format(r["symptom"]),
            "",
            "**What syntropyrl measures.** {}".format(r["measure"]),
            "",
            "**Likely causes**",
            "",
        ]
        out += ["- {}".format(c) for c in r["causes"]]
        out += ["", "**Fixes, in order**", ""]
        out += ["{}. {}".format(i + 1, f) for i, f in enumerate(r["fixes"])]
        out += [
            "",
            "**Why it matters.** {}".format(r["cost"]),
            "",
            "```bash",
            r["repro"],
            "```",
        ]
    out += [
        "",
        "---",
        "",
        "## Contributing an entry",
        "",
        "If you have debugged an RL run at 2am, you know something that is not written",
        "down anywhere. A complete contribution is an Atlas entry, a repro scenario, a",
        "detector, and a test. See [CONTRIBUTING.md](CONTRIBUTING.md).",
        "",
    ]
    return "\n".join(out)


# --------------------------------------------------------------------------
# docs/atlas.html
# --------------------------------------------------------------------------
def _li(items):
    return "\n".join("          <li>{}</li>".format(html.escape(i)) for i in items)


def build_html(rows, orphan) -> str:
    cards = []
    current = None
    for r in rows:
        if r["family"] != current:
            current = r["family"]
            cards.append(
                '      <div class="family-head" data-family="{f}">\n'
                "        <h2>{title}</h2>\n"
                "        <p>{blurb}</p>\n"
                "      </div>".format(
                    f=current,
                    title=html.escape(current.title()),
                    blurb=html.escape(FAMILY_BLURB.get(current, "")),
                )
            )
        haystack = " ".join(
            [r["code"], r["title"], r["symptom"], " ".join(r.get("aka", []))]
        ).lower()
        cards.append(
            """      <article class="entry" id="{code}" data-family="{family}" data-search="{search}">
        <header class="entry-head">
          <div class="entry-title">
            <code class="code-chip">{code}</code>
            <h3>{title}</h3>
          </div>
          <div class="entry-meta">
            <span class="tag tag-{family}">{family}</span>
            <span class="tag {detcls}">{detlabel}</span>
            <a class="anchor-link" href="#{code}" aria-label="Link to {code}">#</a>
          </div>
        </header>
        {aka}
        <div class="entry-body">
          <div class="field">
            <span class="field-label">Symptom</span>
            <p>{symptom}</p>
          </div>
          <div class="field">
            <span class="field-label">What syntropyrl measures</span>
            <p>{measure}</p>
          </div>
          <div class="two-col">
            <div class="field">
              <span class="field-label">Likely causes</span>
              <ul>
{causes}
              </ul>
            </div>
            <div class="field">
              <span class="field-label">Fixes, in order</span>
              <ol>
{fixes}
              </ol>
            </div>
          </div>
          <div class="field cost">
            <span class="field-label">Why it matters</span>
            <p>{cost}</p>
          </div>
          <div class="repro">
            <span class="repro-label">Reproduce locally</span>
            <code>$ {repro}</code>
          </div>
        </div>
      </article>""".format(
                code=r["code"],
                family=r["family"],
                search=html.escape(haystack, quote=True),
                title=html.escape(r["title"]),
                detcls="tag-ok" if r["detector"] else "tag-todo",
                detlabel="detector shipped" if r["detector"] else "detector wanted",
                aka=(
                    '        <p class="aka">also called: {}</p>'.format(
                        html.escape(", ".join(r["aka"]))
                    )
                    if r.get("aka")
                    else ""
                ),
                symptom=html.escape(r["symptom"]),
                measure=html.escape(r["measure"]),
                causes=_li(r["causes"]),
                fixes=_li(r["fixes"]),
                cost=html.escape(r["cost"]),
                repro=html.escape(r["repro"]),
            )
        )

